import assert from 'node:assert/strict';
import { WBQ_ITEMS, WBQ_AREAS } from './learning-wbq.js';
import { hsqQuestions, areas as HSQ_AREAS } from './learning-hsq.js';
const records = new Map();
globalThis.localStorage = { getItem: key => records.get(key) ?? null, setItem: (key, value) => records.set(key, String(value)) };
const { renderLearningQuiz, handleLearningQuizClick, handleLearningQuizChange, getLearningProgressSnapshot } = await import('./learning-ui.js');
const all = [...WBQ_ITEMS, ...hsqQuestions];
assert.equal(all.length, 450);
assert.equal(new Set([...WBQ_AREAS, ...HSQ_AREAS].map(area => area.id)).size, 9);
const gameAndFinance = { game: { date: '2027-01-01', cash: 30000, orders: [] }, finance: { cash: 30000, ledger: [] } };
const before = JSON.stringify(gameAndFinance);
let html = renderLearningQuiz('2027-01-01');
assert.match(html, /450/);
assert.match(html, /WBQ/);
assert.match(html, /HSQ/);
const first = all[0];
const eventFor = (selector, element) => ({ target: { closest: value => value === selector ? element : null } });
assert.equal(handleLearningQuizClick(eventFor('[data-learning-answer]', { dataset: { learningAnswer: first.correctOption } }), '2027-01-01'), true);
html = renderLearningQuiz('2027-01-01');
assert.match(html, /Richtig/);
assert.ok(html.includes(first.explanation));
assert.ok(html.includes(first.companyEffect));
let progress = getLearningProgressSnapshot();
assert.equal(progress[first.id].attempts, 1);
assert.equal(progress[first.id].correct, 1);
assert.equal(progress[first.id].nextReviewAt, '2027-01-02');
assert.equal(JSON.stringify(gameAndFinance), before, 'learning answer must not mutate game or finance state');
assert.equal(handleLearningQuizClick(eventFor('[data-learning-next]', {}), '2027-01-01'), true);
const second = all[1];
assert.equal(handleLearningQuizClick(eventFor('[data-learning-answer]', { dataset: { learningAnswer: 'ABCD'.replace(second.correctOption, '').slice(0,1) } }), '2027-01-01'), true);
html = renderLearningQuiz('2027-01-01');
assert.match(html, /Noch nicht richtig/);
assert.match(html, new RegExp(`Lösung ${second.correctOption}`));
assert.equal(JSON.stringify(gameAndFinance), before, 'incorrect learning answer must not mutate game or finance state');
const chosenArea = WBQ_AREAS[1];
assert.equal(handleLearningQuizChange(eventFor('[data-learning-area]', { value: chosenArea.id })), true);
html = renderLearningQuiz('2027-01-01');
assert.ok(html.includes(chosenArea.name || chosenArea.title));
assert.match(html, /Fall 1 von 50/);
assert.equal(JSON.stringify(gameAndFinance), before);
console.log('PASS: 450-item library; nine areas; correct/incorrect feedback; spaced review; area filtering; learning-only storage; game and finance state unchanged');

